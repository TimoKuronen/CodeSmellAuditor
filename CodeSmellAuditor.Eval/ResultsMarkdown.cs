using System.Globalization;
using System.Text;

namespace CodeSmellAuditor.Eval;

/// <summary>
/// Renders the results table and the comparison against the previous run of the same model.
/// </summary>
public static class ResultsMarkdown
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    public static string RenderDelta(ResultRow? previous, ResultRow current)
    {
        var builder = new StringBuilder();
        builder.AppendLine($"### {current.Model}: {current.RunId} ({Describe(current)})");
        builder.AppendLine();

        if (previous is null)
        {
            builder.AppendLine("First row for this model; nothing to compare against.");
            return builder.ToString();
        }

        RunDelta delta = RunDelta.Compute(previous, current);
        builder.AppendLine($"Compared with {previous.RunId} ({Describe(previous)}).");
        builder.AppendLine(delta.Changed.Count == 0
            ? "Changed since then: nothing tracked (same prompt, rules, core code and corpus)."
            : $"Changed since then: {string.Join(", ", delta.Changed)}.");

        if (!delta.Comparable)
        {
            builder.AppendLine();
            builder.AppendLine("The corpus changed, so hit totals are not comparable; treat this row as a new baseline.");
            return builder.ToString();
        }

        builder.AppendLine();
        builder.AppendLine("| Metric | Previous | Current | Change | Verdict |");
        builder.AppendLine("|--------|----------|---------|--------|---------|");
        foreach (DeltaLine line in delta.Lines)
        {
            builder.AppendLine(
                $"| {line.Metric} | {Number(line.Previous)} | {Number(line.Current)} | {Signed(line.Change)} | {line.Verdict} |");
        }

        return builder.ToString();
    }

    public static string Render(IReadOnlyList<ResultRow> rows)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Benchmark results");
        builder.AppendLine();
        builder.AppendLine("Generated by the Eval project; do not edit. Hits count answer-key items found (model or pre-check) out of the corpus total. Token figures are per corpus pass; reading figures are estimates.");
        builder.AppendLine();

        builder.AppendLine("## Latest comparison per model");
        builder.AppendLine();

        foreach (string model in rows.Select(r => r.Model).Distinct().Reverse())
        {
            List<ResultRow> modelRows = rows.Where(r => r.Model == model).ToList();
            ResultRow current = modelRows[^1];
            ResultRow? previous = modelRows.Count > 1 ? modelRows[^2] : null;
            builder.AppendLine(RenderDelta(previous, current));
        }

        builder.AppendLine("## All runs (newest first)");
        builder.AppendLine();
        builder.AppendLine("| Run | Label | Model | Sha | Blatant | Judgment | Model hits | Pre-check | Noise | Ungrounded | Clean | Trunc/Fail | Status miss | s/file | Ollama in/out | Read est (report / sidecar / verify) |");
        builder.AppendLine("|-----|-------|-------|-----|---------|----------|------------|-----------|-------|------------|-------|------------|-------------|--------|---------------|-------------------------------------|");

        foreach (ResultRow row in rows.Reverse())
        {
            builder.AppendLine(
                $"| {row.RunId} | {row.Label} | {row.Model} | {row.GitSha}{(row.Dirty ? "*" : string.Empty)} " +
                $"| {Number(row.CombinedBlatant)}/{row.BlatantTotal} | {Number(row.CombinedJudgment)}/{row.JudgmentTotal} " +
                $"| {Number(row.ModelHits)} | {Number(row.PreCheckHits)} | {Number(row.Noise)} | {Number(row.Ungrounded)} " +
                $"| {Number(row.CleanFindings)} | {Number(row.Truncated)}/{Number(row.Failed)} | {Number(row.StatusMismatches)} " +
                $"| {Number(row.SecondsPerFile)} | {Number(row.PromptTokens)}/{Number(row.OutputTokens)} " +
                $"| {Number(row.ReadReportTokens)} / {Number(row.ReadSidecarTokens)} / {Number(row.ReadVerifyTokens)} |");
        }

        builder.AppendLine();
        builder.AppendLine("An asterisk after the sha marks a run on uncommitted changes.");
        return builder.ToString();
    }

    private static string Describe(ResultRow row) =>
        $"{(string.IsNullOrWhiteSpace(row.Label) ? "no label" : row.Label)}, {row.Repeats} repeats, sha {row.GitSha}{(row.Dirty ? "*" : string.Empty)}";

    private static string Number(double value) => value.ToString("0.##", Invariant);

    private static string Signed(double value) =>
        Math.Abs(value) < 0.005 ? "0" : (value > 0 ? "+" : string.Empty) + value.ToString("0.##", Invariant);
}
